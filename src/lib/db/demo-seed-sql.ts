/**
 * Builds the SQL that seeds the single Demo Center from the same sample data the app shows (src/lib/data.ts).
 * Codes (S-1001, C-201, T-101) are kept, so the in-memory demo ledger still lines up with these students.
 * UUIDs are derived from the codes, so the output is identical on every run.
 * Regenerate with `bun scripts/gen-demo-seed.ts`; a test fails if the committed migration is out of date.
 */
import { createHash } from "node:crypto";
import { students, teachers, classes, seedEnrollmentRules, enrollmentKey } from "../data";
import { centerProfile } from "../center-config";
import { ruleToColumns, toPiastres, type RuleColumns } from "./rules";

export const DEMO_CENTER_ID = demoId("center");
export function demoId(key: string) {
  const h = createHash("md5").update(`markezly-demo:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const lit = (v: string | number | boolean | null) =>
  v === null ? "null" : typeof v === "string" ? `'${v.replace(/'/g, "''")}'` : String(v);
const row = (values: (string | number | boolean | null)[]) => `  (${values.map(lit).join(", ")})`;
const ruleValues = (c: RuleColumns) => [
  c.rule_kind,
  c.rule_fee_piastres,
  c.rule_rate_piastres,
  c.rule_charge_no_show,
  c.rule_package_sessions,
  c.rule_package_price_piastres,
  c.rule_count_no_show,
];
const RULE_COLS =
  "rule_kind, rule_fee_piastres, rule_rate_piastres, rule_charge_no_show, rule_package_sessions, rule_package_price_piastres, rule_count_no_show";
const branchId = (name: string) => demoId(`branch:${name}`);
const kind = (k: string) => (k === "Tutoring" ? "tutoring" : "language_course");

export function demoSeedSql(): string {
  const out: string[] = [
    "-- GENERATED by scripts/gen-demo-seed.ts from src/lib/data.ts. Do not edit by hand; regenerate instead.",
    "-- Seeds the one Demo Center with the app's synthetic sample data. Customer centers are never seeded:",
    "-- every row below belongs to the demo center id, and public.create_center() adds no sample rows.",
    "",
    `insert into public.centers (id, name, is_demo) values (${lit(DEMO_CENTER_ID)}, ${lit(`${centerProfile.name} (Demo)`)}, true);`,
    "",
    "insert into public.branches (id, center_id, name) values",
    centerProfile.branches.map((b) => row([branchId(b), DEMO_CENTER_ID, b])).join(",\n") + ";",
    "",
    "insert into public.teachers (id, center_id, code, name, subject, phone, branch_id, pay_model, pay_amount_piastres, pay_percent) values",
    teachers
      .map((t) =>
        row([
          demoId(t.id),
          DEMO_CENTER_ID,
          t.id,
          t.name,
          t.subject,
          t.phone,
          branchId(t.branch),
          t.model.type,
          t.model.type === "percentage" ? null : toPiastres(t.model.amount),
          t.model.type === "percentage" ? t.model.percent : null,
        ]),
      )
      .join(",\n") + ";",
    "",
    `insert into public.classes (id, center_id, code, name, kind, teacher_id, branch_id, days, start_time, capacity, fee_piastres, ${RULE_COLS}) values`,
    classes
      .map((c) =>
        row([
          demoId(c.id),
          DEMO_CENTER_ID,
          c.id,
          c.name,
          kind(c.kind),
          demoId(c.teacherId),
          branchId(c.branch),
          c.days,
          c.time,
          c.capacity,
          toPiastres(c.fee),
          ...ruleValues(ruleToColumns(c.rule)),
        ]),
      )
      .join(",\n") + ";",
    "",
    "insert into public.students (id, center_id, code, name, phone, guardian_name, guardian_phone, branch_id, grade, status, joined_on, demo_attendance_pct, created_by) values",
    students
      .map((s) =>
        row([
          demoId(s.id),
          DEMO_CENTER_ID,
          s.id,
          s.name,
          s.phone,
          s.guardian,
          s.guardianPhone,
          branchId(s.branch),
          s.grade,
          s.status.toLowerCase(),
          s.joined,
          s.attendance,
          null,
        ]),
      )
      .join(",\n") + ";",
    "",
    `insert into public.enrollments (id, center_id, student_id, class_id, ${RULE_COLS}) values`,
    students
      .flatMap((s) =>
        s.classIds.map((cid) =>
          row([
            demoId(`enrollment:${s.id}|${cid}`),
            DEMO_CENTER_ID,
            demoId(s.id),
            demoId(cid),
            ...ruleValues(ruleToColumns(seedEnrollmentRules[enrollmentKey(s.id, cid)])),
          ]),
        ),
      )
      .join(",\n") + ";",
    "",
  ];
  return out.join("\n");
}
